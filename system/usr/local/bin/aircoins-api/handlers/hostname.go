package handlers

import (
	"bufio"
	"context"
	"log"
	"net"
	"os"
	"strings"
	"sync"
	"time"
)

// hostnameCacheEntry stores a resolved hostname with an expiration time.
type hostnameCacheEntry struct {
	hostname string
	expires  time.Time
}

// hostnameCache is a package-level cache for IP→hostname lookups.
// Key: client IP (string). Value: hostnameCacheEntry.
var hostnameCache sync.Map

const hostnameCacheTTL = 60 * time.Second
const hostnameResolveTimeout = 200 * time.Millisecond

// knownLeasePaths lists the dnsmasq lease file locations to try in order.
// The per-interface dnsmasq instances generated by startPortalDHCP do not
// set dhcp-leasefile, so dnsmasq falls back to its compiled-in default
// /var/lib/misc/dnsmasq.leases. /var/lib/pisowifi/dnsmasq.leases is tried
// as a secondary path for legacy installs.
var knownLeasePaths = []string{
	"/var/lib/misc/dnsmasq.leases",
	"/var/lib/pisowifi/dnsmasq.leases",
}

// ResolveHostname returns the hostname for the given client IP (and
// optional MAC). It returns "" when no hostname can be determined or
// when the inputs are not meaningful (empty IP, anonymous MAC "-").
//
// Resolution chain (first match wins):
//  1. Cache hit (60-second TTL).
//  2. dnsmasq leases file — parse known paths, match by IP (or MAC).
//  3. DNS PTR lookup (net.LookupAddr) with a short timeout.
//
// If resolution takes longer than hostnameResolveTimeout the lookup is
// abandoned and "" is returned so the sessions API is never blocked.
func ResolveHostname(ip, mac string) string {
	// Skip anonymous / empty clients.
	if ip == "" || mac == "-" {
		return ""
	}

	// --- 1. Cache hit ---------------------------------------------------
	if v, ok := hostnameCache.Load(ip); ok {
		entry := v.(hostnameCacheEntry)
		if time.Now().Before(entry.expires) {
			return entry.hostname
		}
		// Expired — fall through to resolution.
		hostnameCache.Delete(ip)
	}

	// --- Race against a deadline so we never block the caller -----------
	type result struct {
		name string
	}
	ch := make(chan result, 1)
	go func() {
		name := resolveHostnameSlow(ip, mac)
		ch <- result{name}
	}()

	select {
	case r := <-ch:
		hostnameCache.Store(ip, hostnameCacheEntry{
			hostname: r.name,
			expires:  time.Now().Add(hostnameCacheTTL),
		})
		return r.name
	case <-time.After(hostnameResolveTimeout):
		// Resolution too slow — return empty and let the next poll retry.
		return ""
	}
}

// resolveHostnameSlow runs the full resolution chain without a deadline.
func resolveHostnameSlow(ip, mac string) string {
	// --- 2. dnsmasq leases file -----------------------------------------
	if name := lookupLeaseFile(ip, mac); name != "" {
		return name
	}

	// --- 3. DNS PTR lookup ----------------------------------------------
	ctx, cancel := context.WithTimeout(context.Background(), 500*time.Millisecond)
	defer cancel()
	resolver := net.DefaultResolver
	names, err := resolver.LookupAddr(ctx, ip)
	if err == nil && len(names) > 0 {
		name := strings.TrimSuffix(names[0], ".")
		if name != "" && name != ip {
			return name
		}
	}

	return ""
}

// lookupLeaseFile scans the known dnsmasq lease file paths for a matching
// entry. dnsmasq lease format (one per line):
//
//	<lease_expiry_epoch> <mac> <ip> <hostname> <client_id>
//
// A hostname of "*" means the client did not supply one.
func lookupLeaseFile(ip, mac string) string {
	for _, path := range knownLeasePaths {
		f, err := os.Open(path)
		if err != nil {
			continue // file doesn't exist or is unreadable — try next
		}
		scanner := bufio.NewScanner(f)
		var found string
		for scanner.Scan() {
			line := scanner.Text()
			fields := strings.Fields(line)
			// Expect at least 4 fields: expiry mac ip hostname
			if len(fields) < 4 {
				continue
			}
			leaseIP := fields[2]
			leaseMAC := fields[1]
			leaseHost := fields[3]

			// Match by IP first, then MAC as fallback.
			if leaseIP == ip || (mac != "" && strings.EqualFold(leaseMAC, mac)) {
				if leaseHost != "" && leaseHost != "*" {
					found = leaseHost
					break
				}
			}
		}
		f.Close()
		if found != "" {
			return found
		}
		if err := scanner.Err(); err != nil {
			log.Printf("lookupLeaseFile: error reading %s: %v", path, err)
		}
	}
	return ""
}
